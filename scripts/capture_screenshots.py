def log(message: str) -> None:
    print(_console.ascii_safe(message), flush=True)


def fetch_ids() -> dict[str, str]:
    """Find existing records to screenshot, so the shots show real data."""
    import httpx

    ids: dict[str, str] = {}
    try:
        with httpx.Client(timeout=30.0) as client:
            cvs = client.get(f"{BACKEND}/cv?limit=5").json()
            if cvs["items"]:
                ids["cv_id"] = cvs["items"][0]["cv_id"]

            roles = client.get(f"{BACKEND}/roles?limit=5").json()
            if roles["items"]:
                ids["role_id"] = roles["items"][0]["role_analysis_id"]

            gaps = client.get(f"{BACKEND}/gap?limit=5").json()
            if gaps["items"]:
                ids["gap_id"] = gaps["items"][0]["gap_analysis_id"]

            interviews = client.get(f"{BACKEND}/interview?limit=20").json()["items"]
            # A scored interview for the Results screenshots...
            scored = [i for i in interviews if i.get("has_report")]
            chosen = scored[0] if scored else (interviews[0] if interviews else None)
            if chosen:
                ids["interview_id"] = chosen["id"]
            # ...and an ACTIVE one, so the live voice interface can be shown
            # rather than the "interview complete" screen.
            active = [i for i in interviews if i.get("status") == "active" and i.get("total_questions", 0) > 0]
            if active:
                ids["active_interview_id"] = active[0]["id"]
            elif chosen:
                ids["active_interview_id"] = chosen["id"]
    except Exception as exc:
        log(f"! could not read existing records from the backend: {exc}")
    return ids


def main() -> int:
    parser = argparse.ArgumentParser(description="Screenshot the running application.")
    parser.add_argument("--only", nargs="*", help="capture just these shot names")
    parser.add_argument("--dark", action="store_true", help="also capture a dark-theme set")
    parser.add_argument("--full-page", action="store_true", default=True)
    args = parser.parse_args()

    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        log("Playwright is not installed. Run:")
        log("    pip install playwright")
        log("    python -m playwright install chromium")
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    ids = fetch_ids()

    log("=" * 70)
    log("CAPTURING SCREENSHOTS OF THE RUNNING APPLICATION")
    log("=" * 70)
    log(f"Frontend : {FRONTEND}")
    log(f"Output   : {OUT_DIR}")
    log(f"Records  : {ids if ids else 'none found - run the evaluation first'}")

    missing = [key for key in ("cv_id", "role_id", "gap_id", "interview_id") if key not in ids]
    if missing:
        log(f"\n! No existing {', '.join(missing)}. Those screenshots will be skipped.")
        log("  Run this first, with the backend up:")
        log("      python scripts/run_evaluation.py --mode text --max-turns 6")

    wanted = SHOTS if not args.only else [s for s in SHOTS if s["name"] in args.only]
    captured: list[dict[str, Any]] = []
    index = 0

    with sync_playwright() as playwright:
        browser = playwright.chromium.launch()
        themes = [("light", False)] + ([("dark", True)] if args.dark else [])

        for theme_name, is_dark in themes:
            context = browser.new_context(
                viewport=VIEWPORT,
                device_scale_factor=2,  # crisp enough to embed in a report
                color_scheme="dark" if is_dark else "light",
            )
            page = context.new_page()

            # Set the theme the app actually reads, before any page script runs.
            page.add_init_script(
                f"try {{ localStorage.setItem('cip.theme', '{'\"dark\"' if is_dark else '\"light\"'}'); }} catch (e) {{}}"
            )

            for shot in wanted:
                route = shot["route"]
                placeholder = next((k for k in ids if "{" + k + "}" in route), None)
                if "{" in route and placeholder is None:
                    log(f"  skip {shot['name']}: no record available for its route")
                    continue
                for key, value in ids.items():
                    route = route.replace("{" + key + "}", value)

                index += 1
                suffix = f"_{theme_name}" if is_dark else ""
                filename = f"{index:02d}_{shot['name']}{suffix}.png"
                target = OUT_DIR / filename

                try:
                    page.goto(f"{FRONTEND}{route}", wait_until="networkidle", timeout=60_000)

                    if shot.get("click"):
                        try:
                            page.locator(shot["click"]).first.click(timeout=15_000)
                            page.wait_for_timeout(900)
                        except Exception:
                            log(f"    (could not click {shot['click']!r}; capturing anyway)")

                    if shot.get("run_playground"):
                        try:
                            page.get_by_role("button", name="Normalise").first.click(timeout=15_000)
                            page.wait_for_timeout(2500)
                        except Exception:
                            log("    (could not run the playground; capturing anyway)")

                    if shot.get("wait_for"):
                        try:
                            page.wait_for_selector(shot["wait_for"], timeout=25_000)
                        except Exception:
                            log(f"    (never saw {shot['wait_for']!r}; capturing anyway)")

                    if shot.get("scroll_to"):
                        try:
                            page.locator(shot["scroll_to"]).first.scroll_into_view_if_needed(timeout=10_000)
                            page.wait_for_timeout(700)
                        except Exception:
                            pass

                    # Let charts finish their entry animation.
                    page.wait_for_timeout(1400)
                    page.screenshot(path=str(target), full_page=args.full_page)

                    size = target.stat().st_size
                    log(f"  [{index:02d}] {filename}  ({size / 1024:.0f} KB)")
                    captured.append(
                        {
                            "figure": index,
                            "file": filename,
                            "name": shot["name"],
                            "theme": theme_name,
                            "route": route,
                            "caption": shot["caption"],
                            "bytes": size,
                        }
                    )
                except Exception as exc:
                    log(f"  ! {shot['name']} failed: {type(exc).__name__}: {exc}")

            context.close()
        browser.close()

    # Manifest, so the report can cite figures without guessing filenames.
    manifest = OUT_DIR / "MANIFEST.md"
    lines = [
        "# Screenshots",
        "",
        "Genuine screenshots of the running application, captured automatically with",
        "Playwright against the real frontend and backend. No image has been edited, and",
        "nothing shown here is a mock-up.",
        "",
        f"Captured: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"Viewport: {VIEWPORT['width']}x{VIEWPORT['height']} at 2x device scale",
        "",
        "Regenerate with:",
        "",
        "```bash",
        "python scripts/capture_screenshots.py",
        "```",
        "",
        "| Figure | File | Page | Caption |",
        "|---|---|---|---|",
    ]
    for shot in captured:
        caption = shot["caption"].replace("|", "\\|")
        lines.append(f"| {shot['figure']} | `{shot['file']}` | `{shot['route']}` | {caption} |")

    manifest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    (OUT_DIR / "manifest.json").write_text(json.dumps(captured, indent=2), encoding="utf-8")

    log("\n" + "=" * 70)
    log(f"Captured {len(captured)} screenshot(s)")
    log(f"Manifest: {manifest}")
    return 0 if captured else 1


if __name__ == "__main__":
    sys.exit(main())
